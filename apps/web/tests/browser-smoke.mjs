import { chromium } from 'playwright';
import { readFile, mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
const directory = new URL('./artifacts/', import.meta.url);
await mkdir(directory, { recursive: true });
const credentials = JSON.parse(await readFile(new URL('../../../.local/development-accounts.json', import.meta.url), 'utf8'));
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2 });
const errors = [];
let maxCanvases = 0;
let controlsWithinViewport = true;
let keyboardMenuIsolated = true;
let postPreflightRequests = 0;
page.on('pageerror', error => errors.push(error.message));
await page.goto(`http://127.0.0.1:5175/?event_id=${credentials.event_id}#/`);
await page.getByText('45 秒一局 · 三款任选', { exact: true }).waitFor();
await page.screenshot({ path: fileURLToPath(new URL('lobby-mobile.png', directory)), fullPage: true });
const overflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth);
for (let round = 0; round < 10; round++) {
  const game = ['stack', 'runner', 'herd'][round % 3];
  await page.goto(`http://127.0.0.1:5175/?event_id=${credentials.event_id}#/practice/${game}`);
  await page.getByRole('button', { name: '开始不计分练习' }).click();
  await page.locator('canvas').waitFor();
  maxCanvases = Math.max(maxCanvases, await page.locator('canvas').count());
  await page.getByRole('button', { name: '开启音效' }).focus();
  await page.keyboard.press('Space');
  await page.waitForTimeout(100);
  keyboardMenuIsolated &&= Number(await page.locator('.game-stage').getAttribute('data-accepted-actions')) === 0;
  await page.route('**/assets/**/*.png', route => { postPreflightRequests++; return route.abort(); });
  await page.evaluate(() => scrollTo(0, 0));
  const controls = await page.locator('.game-controls').boundingBox();
  controlsWithinViewport &&= controls.y >= 0 && controls.y + controls.height <= 844;
  if (game === 'herd') {
    const joystick = page.getByRole('group', { name: '拖动摇杆移动牧羊犬' });
    const box = await joystick.boundingBox();
    await page.mouse.move(box.x + box.width / 2, box.y + 20); await page.mouse.down(); await page.waitForTimeout(100); await page.mouse.up();
  } else await page.getByRole('button', { name: game === 'stack' ? '点击放下' : '点击跳跃' }).click();
  await page.waitForTimeout(150);
  if (round < 3) await page.screenshot({ path: fileURLToPath(new URL(`${game}-mobile.png`, directory)), fullPage: true });
  await page.unroute('**/assets/**/*.png');
}
await page.setViewportSize({ width: 1280, height: 720 });
await page.goto('http://127.0.0.1:5175/#/screen');
await page.getByAltText('公共活动入口二维码').waitFor();
await page.screenshot({ path: fileURLToPath(new URL('display.png', directory)), fullPage: true });
const result = { mobileViewportSimulation: '390x844 DPR2 Chromium', actualDevice: false, overflow, rounds: 10, maxCanvases, controlsWithinViewport, keyboardMenuIsolated, postPreflightRequests, errors };
await writeFile(new URL('browser-smoke.json', directory), JSON.stringify(result, null, 2));
console.log(JSON.stringify(result));
await browser.close();
if (overflow || errors.length || !controlsWithinViewport || !keyboardMenuIsolated || maxCanvases !== 1 || postPreflightRequests !== 0) process.exitCode = 1;
